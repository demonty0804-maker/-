# 1. [함수(def) & 조건문(if-elif-else)] 색상이 너무 밝으면 어두운 배경 배지를 입혀 글자가 잘 보이게 만드는 함수
def format_colored_text(text, hex_code):
    # HEX 코드를 R, G, B 숫자로 변환
    hex_clean = hex_code.lstrip('#')
    r = int(hex_clean[0:2], 16)
    g = int(hex_clean[2:4], 16)
    b = int(hex_clean[4:6], 16)
    
    # 밝기 계산 (155보다 크면 밝은 색으로 판단)
    brightness = (r * 299 + g * 587 + b * 114) / 1000
    
    if brightness > 155:
        # 밝은 색(예: 레몬 옐로우)은 짙은 배경 배지 위에 출력해서 선명하게 보이도록 처리
        return f"<span style='color:{hex_code}; background-color:#22262b; padding:2px 8px; border-radius:6px; font-weight:bold;'>{text}</span>"
    else:
        # 어둡거나 진한 색은 글자 자체에만 색상 적용
        return f"<span style='color:{hex_code}; font-weight:bold;'>{text}</span>"


