# 3. [함수(def) & 반복문(for)] 추천 개수만큼 결과를 출력하는 함수
def print_recommendations(color_list, count):
    print("\n" + "=" * 55)
    print("🎨 [결과 출력 화면]")
    print("=" * 55)

    # 반복문(for)을 사용해 사용자가 선택한 개수(1~3개)만큼 순서대로 출력
    for i in range(count):
        item = color_list[i]
        name = item[0]
        r, g, b = item[1], item[2], item[3]
        message = item[4]
        warning = item[5]

        # 색 이름에 실제 색상을 입힌 문자열 생성
        colored_name = color_text(name, r, g, b)
        # 문장 속 색 이름에도 동일하게 색상 적용
        colored_message = message.replace(name, colored_name)

        print(f"\n[{i + 1}번째 추천 색상 : {colored_name}]")
        print(f'- "{colored_message}"')
        print(f"- 주의!: {warning}")

    print("\n" + "=" * 55)


