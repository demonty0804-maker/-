# 3. [함수(def) & 반복문(for)] 스트림릿 화면에 결과를 출력하는 함수
def display_recommendations(color_list, count):
    st.subheader("📋 결과 출력 화면")
    
    # 반복문(for)을 사용해 사용자가 슬라이더로 선택한 개수(1~3개)만큼 카드 형태로 출력
    for i in range(count):
        item = color_list[i]
        name = item[0]
        hex_code = item[1]
        message = item[2]
        warning = item[3]
        
        # 색 이름에 실제 색상을 입힌 HTML 태그 생성
        colored_name = format_colored_text(name, hex_code)
        # 추천 문장 속 색 이름에도 동일하게 색상 적용
        colored_message = message.replace(name, colored_name)
        
        with st.container(border=True):
            # 색상 원형 아이콘 + 색상이 입혀진 색 이름 출력
            st.markdown(
                f"<div style='display:flex; align-items:center; gap:10px; font-size:19px; margin-bottom:8px;'>"
                f"<span style='display:inline-block; width:20px; height:20px; border-radius:50%; background-color:{hex_code}; border:1px solid #ccc;'></span>"
                f"{colored_name} <span style='font-size:14px; color:gray;'>({hex_code})</span>"
                f"</div>",
                unsafe_allow_html=True
            )
            # 추천 메시지 출력
            st.markdown(f'💬 "{colored_message}"', unsafe_allow_html=True)
            # 주의사항 출력
            st.warning(f"⚠️ **주의!**: {warning}")


